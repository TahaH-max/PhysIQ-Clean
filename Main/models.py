"""Database models for PhysIQ core features."""

from django.contrib.auth.models import User
from django.db import models


DAY_ORDER = (
    "Monday",
    "Tuesday",
    "Wednesday",
    "Thursday",
    "Friday",
    "Saturday",
    "Sunday",
)

DAY_CHOICES = [(day, day) for day in DAY_ORDER]
MEAL_CHOICES = [
    ("Breakfast", "Breakfast"),
    ("Lunch", "Lunch"),
    ("Dinner", "Dinner"),
    ("Snack", "Snack"),
]


class UserProfile(models.Model):
    """User onboarding data collected before dashboard access."""
    user = models.OneToOneField(User, on_delete=models.CASCADE)
    age = models.PositiveIntegerField(null=True, blank=True)
    weight = models.CharField(max_length=200, null=True, blank=True)
    height = models.CharField(max_length=200, null=True, blank=True)
    gender = models.CharField(
        max_length=50,
        choices=[("male", "Male"), ("female", "Female")],
        default="male",
    )
    fitness_goal = models.CharField(max_length=200, blank=True)
    activity_level = models.CharField(
        max_length=50,
        choices=[
            ("sedentary", "Sedentary"),
            ("light", "Lightly Active"),
            ("moderate", "Moderately Active"),
            ("active", "Active"),
            ("very_active", "Very Active"),
        ],
        default="moderate",
    )
    dietary_preferences = models.CharField(max_length=200, blank=True)
    allergies = models.CharField(max_length=200, blank=True)
    budget = models.DecimalField(max_digits=8, decimal_places=2, null=True, blank=True)
    schedule = models.JSONField(default=dict, blank=True, null=True)
    profile_completed = models.BooleanField(default=False)

    def is_complete(self):
        """Return True when required profile fields are filled in."""
        required = [self.age, self.height, self.weight, self.fitness_goal]
        return all(bool(x) for x in required)

    def __str__(self):
        return self.user.username


class Plan(models.Model):
    """Stored workout or nutrition plans generated by the assistant."""
    PLAN_TYPES = [
        ("workout", "Workout Plan"),
        ("nutrition", "Nutrition Plan"),
    ]

    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name="plans")
    plan_type = models.CharField(max_length=20, choices=PLAN_TYPES)
    encouragement_message = models.TextField(blank=True, default="")
    calorie_target = models.FloatField(null=True, blank=True)
    protein_g = models.FloatField(null=True, blank=True)
    carbs_g = models.FloatField(null=True, blank=True)
    fat_g = models.FloatField(null=True, blank=True)
    raw_response = models.JSONField(null=True, blank=True)
    created_at = models.DateTimeField(auto_now_add=True)

    def __str__(self):
        return f"{self.user.username} - {self.plan_type}"


class WorkoutDay(models.Model):
    """Normalized workout day data tied to a Plan."""
    plan = models.ForeignKey(
        Plan, on_delete=models.CASCADE, related_name="workout_days"
    )
    day = models.CharField(max_length=12, choices=DAY_CHOICES)
    recommended_time = models.CharField(max_length=50, blank=True, default="")
    focus = models.CharField(max_length=30, blank=True, default="")
    session_type = models.CharField(max_length=30, blank=True, default="")
    notes = models.TextField(blank=True, default="")
    sort_order = models.PositiveSmallIntegerField(default=0)

    class Meta:
        ordering = ["sort_order", "id"]
        unique_together = ["plan", "day"]

    def __str__(self):
        return f"{self.plan.user.username} - {self.day}"


class WorkoutExercise(models.Model):
    """Exercises within a workout day."""
    workout_day = models.ForeignKey(
        WorkoutDay, on_delete=models.CASCADE, related_name="exercises"
    )
    name = models.CharField(max_length=200)
    sets = models.IntegerField(null=True, blank=True)
    reps = models.IntegerField(null=True, blank=True)
    distance_m = models.FloatField(null=True, blank=True)
    notes = models.TextField(blank=True, default="")
    sort_order = models.PositiveSmallIntegerField(default=0)

    class Meta:
        ordering = ["sort_order", "id"]

    def __str__(self):
        return self.name


class NutritionDay(models.Model):
    """Normalized nutrition day data tied to a Plan."""
    plan = models.ForeignKey(
        Plan, on_delete=models.CASCADE, related_name="nutrition_days"
    )
    day = models.CharField(max_length=12, choices=DAY_CHOICES)
    notes = models.TextField(blank=True, default="")
    day_total_calories = models.FloatField(null=True, blank=True)
    sort_order = models.PositiveSmallIntegerField(default=0)

    class Meta:
        ordering = ["sort_order", "id"]
        unique_together = ["plan", "day"]

    def __str__(self):
        return f"{self.plan.user.username} - {self.day}"


class Meal(models.Model):
    """Meals for a nutrition day."""
    nutrition_day = models.ForeignKey(
        NutritionDay, on_delete=models.CASCADE, related_name="meals"
    )
    name = models.CharField(max_length=20, choices=MEAL_CHOICES)
    meal_total_calories = models.FloatField(null=True, blank=True)
    sort_order = models.PositiveSmallIntegerField(default=0)

    class Meta:
        ordering = ["sort_order", "id"]

    def __str__(self):
        return f"{self.nutrition_day.day} - {self.name}"


class MealItem(models.Model):
    """Items within a meal."""
    meal = models.ForeignKey(
        Meal, on_delete=models.CASCADE, related_name="items"
    )
    food = models.CharField(max_length=200)
    portion = models.CharField(max_length=100)
    calories = models.FloatField(null=True, blank=True)
    protein_g = models.FloatField(null=True, blank=True)
    carbs_g = models.FloatField(null=True, blank=True)
    fat_g = models.FloatField(null=True, blank=True)
    notes = models.TextField(blank=True, default="")
    sort_order = models.PositiveSmallIntegerField(default=0)

    class Meta:
        ordering = ["sort_order", "id"]

    def __str__(self):
        return self.food


class ChatMessage(models.Model):
    """Conversation history between the user and the assistant."""
    user = models.ForeignKey(
        User, on_delete=models.CASCADE, related_name="chat_messages"
    )
    message = models.TextField()
    response = models.TextField()
    timestamp = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-timestamp"]

    def __str__(self):
        return f"{self.user.username} - {self.timestamp.strftime('%Y-%m-%d %H:%M')}"


class DailyProgress(models.Model):
    """Daily workout/nutrition tracking entries."""
    WORKOUT_STATUS_CHOICES = [
        ("done", "Done"),
        ("missed", "Missed"),
        ("rest", "Rest"),
    ]

    NUTRITION_STATUS_CHOICES = [
        ("hit", "Hit"),
        ("missed", "Missed"),
        ("none", "None"),
    ]

    user = models.ForeignKey(
        User, on_delete=models.CASCADE, related_name="daily_progress"
    )
    date = models.DateField()
    workout_status = models.CharField(
        max_length=10, choices=WORKOUT_STATUS_CHOICES, default="missed"
    )
    nutrition_status = models.CharField(
        max_length=10, choices=NUTRITION_STATUS_CHOICES, default="none"
    )
    notes = models.TextField(blank=True, default="")
    created_at = models.DateTimeField(auto_now_add=True)
    updated_at = models.DateTimeField(auto_now=True)

    class Meta:
        ordering = ["-date"]
        unique_together = ["user", "date"]

    def __str__(self):
        return f"{self.user.username} - {self.date}"


class PhotoLocker(models.Model):
    """Progress photos that can be private or shared publicly."""
    VISIBILITY_CHOICES = [
        ("private", "Private"),
        ("public", "Public"),
    ]

    user = models.ForeignKey(User, on_delete=models.CASCADE, related_name="photos")
    image = models.ImageField(upload_to="user_photos/")
    note = models.TextField(blank=True, max_length=300)
    visibility = models.CharField(
        max_length=10, choices=VISIBILITY_CHOICES, default="private"
    )
    uploaded_at = models.DateTimeField(auto_now_add=True)

    class Meta:
        ordering = ["-uploaded_at"]

    def __str__(self):
        return f"{self.user.username} - {self.visibility.capitalize()}"

    @staticmethod
    def public_photos():
        """Return all public photos for the community feed."""
        return (
            PhotoLocker.objects.filter(visibility="public")
            .select_related("user")
            .order_by("-uploaded_at")
        )

